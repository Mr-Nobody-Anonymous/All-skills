def render(data) -> str:
    pairs = data["pairs"]
    notes = list(data["notes"])
    if pairs:
        notes.append("Pairs with: " + ", ".join(f"`{p}`" for p in pairs) + ".")
    front = [
        "---",
        f"name: {data['name']}",
        f"description: {yaml_scalar(data['description'])}",
        f"type: {data['type']}",
        f"category: {data['category']}",
        f"domain: {data['domain']}",
        f"version: 1.0.0",
        f"author: {yaml_scalar(AUTHOR)}",
        "license: MIT",
        f"risk: {data['risk']}",
        f"level: {data['level']}",
        "triggers:",
    ]
    front += [f"  - {yaml_scalar(t)}" for t in data["triggers"]]
    if data["aliases"]:
        front.append("aliases:")
        front += [f"  - {yaml_scalar(a)}" for a in data["aliases"]]
    front.append("keywords:")
    front += [f"  - {yaml_scalar(k)}" for k in data["keywords"]]
    front += ["source: custom", "enabled: true", "---", ""]

    title = TITLE_OVERRIDES.get(data["name"], data["name"].replace("-", " ").title())
    body = [f"# {title}", "", "## Purpose", "",
            data["description"], ""]
    body += ["## When to Use", ""] + [f"- {item}" for item in data["when"]] + [""]
    body += ["## When NOT to Use", ""] + [f"- {item}" for item in data["when_not"]] + [""]
    body += ["## Capabilities", ""] + [f"- {item}" for item in data["capabilities"]] + [""]
    body += ["## Inputs", ""] + [f"- {item}" for item in data["inputs"]] + [""]
    body += ["## Workflow", ""] + [f"{i}. {item}" for i, item in enumerate(data["workflow"], 1)] + [""]
    body += ["## Tools", ""] + [f"- {item}" for item in data["tools"]] + [""]
    body += ["## Examples", ""] + [f"- `{item}`" for item in data["examples"]] + [""]
    body += ["## Safety", ""] + [f"- {item}" for item in data["safety"]] + [""]
    body += ["## Source", "",
             f"All-Skills canonical library (`skills/{data['category']}/{data['name']}`). "
             "First-party skill, maintained in this repository.", ""]
    body += ["## Notes", ""] + [f"- {item}" for item in notes] + [""]
    return "\n".join(front + body)


def yaml_scalar(value: str) -> str:
    """Quote only when YAML would otherwise misparse the string."""
    text = str(value)
    needs = (": " in text or text.startswith(("-", "?", ":", "!", "&", "*", "#", "{", "["))
             or text.endswith(":") or '"' in text or "'" in text or "\n" in text)
    if needs:
        return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return text


def main() -> int:
    existing = {path.parent.name for path in SKILLS.rglob("SKILL.md")}
    written, skipped = [], []
    for data in SKILLS_DATA:
        if data["name"] in existing and not FORCE:
            skipped.append(data["name"])
            continue
        target = SKILLS / data["category"] / data["name"] / "SKILL.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render(data), encoding="utf-8")
        written.append(f"{data['category']}/{data['name']}")
    print(f"wrote {len(written)} skill(s)")
    for item in written:
        print(f"  skills/{item}/SKILL.md")
    if skipped:
        print(f"skipped {len(skipped)} already present: {', '.join(skipped)}")
    return 0


