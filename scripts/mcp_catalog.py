#!/usr/bin/env python3
"""MCP catalog CLI: list, verify, generate and install Model Context Protocol servers.

One command wires any server in ``mcps/catalog.json`` into any supported agent
harness (Claude Code, Cursor, Codex, VS Code, Gemini CLI, Windsurf, Cline, Roo,
OpenCode, Zed, Kimi, Trae, CodeBuddy, Hermes, OpenClaw, Continue, Goose).

Examples:
    python scripts/mcp_catalog.py list
    python scripts/mcp_catalog.py list --profile core --json
    python scripts/mcp_catalog.py doctor
    python scripts/mcp_catalog.py verify
    python scripts/mcp_catalog.py generate            # docs + per-harness bundles
    python scripts/mcp_catalog.py install --harness claude --profile standard --dry-run
    python scripts/mcp_catalog.py install --harness cursor --servers github postgres
    python scripts/mcp_catalog.py install --harness claude --profile full --scope user

Anything that writes prints its plan first; ``--dry-run`` never touches disk.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from skills.mcp import (  # noqa: E402
    Catalog,
    CatalogError,
    InstallResult,
    apply_install,
    catalog_summary,
    expand_profile,
    harness_names,
    plan_install,
    verify_catalog,
)

GENERATED_DIR = ROOT / "mcps" / "generated"
CATALOG_DOC = ROOT / "docs" / "MCP-CATALOG.md"


def _load() -> Catalog:
    return Catalog.load(ROOT)


def cmd_list(args: argparse.Namespace) -> int:
    catalog = _load()
    servers = expand_profile(catalog, args.profile) if args.profile else catalog.servers
    if args.tier:
        servers = [s for s in servers if s.tier == args.tier]
    if args.category:
        servers = [s for s in servers if s.category == args.category]
    if args.json:
        print(json.dumps([s.__dict__ for s in servers], indent=2))
        return 0
    print(f"MCP catalog v{catalog.version} — {len(catalog.servers)} servers, {len(catalog.harnesses)} harnesses\n")
    width = max(len(s.id) for s in servers) if servers else 4
    for server in servers:
        keys = ", ".join(server.required_env) if server.required_env else "no keys"
        print(f"  {server.id.ljust(width)}  {server.tier.ljust(8)}  {server.transport.ljust(4)}  {server.category.ljust(20)}  {keys}")
    print("\nProfiles: " + ", ".join(f"{name}({len(expand_profile(catalog, name))})" for name in sorted(catalog.profiles)))
    return 0


def cmd_doctor(args: argparse.Namespace) -> int:
    catalog = _load()
    summary = catalog_summary(catalog)
    problems = verify_catalog(catalog)
    print("MCP catalog health")
    print(f"  servers   : {summary['servers']} ({summary['by_tier']})")
    print(f"  categories: {len(summary['by_category'])}")
    print(f"  harnesses : {summary['harnesses']} -> {', '.join(harness_names(catalog))}")
    print(f"  profiles  : {summary['profiles']}")
    missing = {s.id: s.missing_env() for s in catalog.servers if s.missing_env()}
    if missing:
        print(f"  credentials not set (installable, will need keys): {len(missing)}")
        for server_id, env in list(missing.items())[:10]:
            print(f"    - {server_id}: {', '.join(env)}")
        if len(missing) > 10:
            print(f"    ... and {len(missing) - 10} more")
    else:
        print("  credentials: every required key is present")
    if problems:
        print(f"\n  {len(problems)} catalog problem(s):", file=sys.stderr)
        for problem in problems:
            print(f"    - {problem}", file=sys.stderr)
        return 1
    print("\n  catalog: OK")
    return 0


def cmd_verify(args: argparse.Namespace) -> int:
    catalog = _load()
    problems = verify_catalog(catalog)
    if problems:
        print(f"[FAIL] MCP catalog has {len(problems)} problem(s):")
        for problem in problems:
            print(f"  - {problem}")
        return 1
    print(f"[PASS] MCP catalog is coherent: {len(catalog.servers)} servers, "
          f"{len(catalog.harnesses)} harnesses, {len(catalog.profiles)} profiles.")
    return 0


def _render_catalog_doc(catalog: Catalog) -> str:
    summary = catalog_summary(catalog)
    lines = [
        "# MCP Catalog — one command, every connector",
        "",
        "`mcps/catalog.json` is the single source of truth for the MCP servers All-Skills can",
        "wire into an agent harness. This page is generated by `python scripts/mcp_catalog.py generate`.",
        "",
        f"- **{summary['servers']} servers** across **{len(summary['by_category'])} categories**",
        f"- **{summary['harnesses']} harnesses** supported with native config dialects",
        f"- **{len(summary['profiles'])} install profiles**: " + ", ".join(
            f"`{name}` ({count})" for name, count in summary["profiles"].items()
        ),
        "",
        "## Install",
        "",
        "```bash",
        "# Everything, into this project's Claude Code config",
        "allskills mcp install --harness claude --profile full",
        "",
        "# A pragmatic default set into Cursor (~/.cursor/mcp.json)",
        "allskills mcp install --harness cursor --profile standard --scope user",
        "",
        "# Pick exact servers, preview first",
        "allskills mcp install --harness vscode --servers github postgres playwright --dry-run",
        "```",
        "",
        "## Servers",
        "",
        "| Server | Tier | Transport | Category | Credentials | Risk | Source |",
        "| :--- | :---: | :---: | :--- | :--- | :---: | :--- |",
    ]
    for server in sorted(catalog.servers, key=lambda s: (s.tier, s.category, s.id)):
        creds = ", ".join(f"`{name}`" for name in server.required_env) if server.required_env else "—"
        if server.required_env and server.required_env_optional:
            creds += " (optional)"
        lines.append(
            f"| [`{server.id}`]({server.docs}) | {server.tier} | {server.transport} | {server.category} | "
            f"{creds} | {server.risk} | {'official' if server.official else server.vendor} |"
        )
    lines += [
        "",
        "## Harnesses",
        "",
        "| Harness | Project config | User config | Dialect |",
        "| :--- | :--- | :--- | :---: |",
    ]
    for harness, spec in sorted(catalog.harnesses.items()):
        scope = spec.get("scope") or {}
        lines.append(
            f"| {spec.get('name', harness)} | `{scope.get('project', '—')}` | `{scope.get('user', '—')}` | {spec.get('format', 'json')} |"
        )
    lines += [
        "",
        "## Notes",
        "",
        "- Installs are additive and idempotent: existing entries are never rewritten,",
        "  and a `*.bak` copy is written before the first mutation.",
        "- Harnesses whose config is TOML (Codex) or YAML (Goose) get a rendered",
        "  fragment instead of an in-place rewrite, so their config can never be corrupted.",
        "- The default connector set stays deliberately small; see",
        "  [`docs/MCP-CONNECTOR-POLICY.md`](MCP-CONNECTOR-POLICY.md). Install",
        "  `--profile full` when you want everything.",
        "",
    ]
    return "\n".join(lines)


def _render_harness_bundle(catalog: Catalog, harness: str) -> tuple[str, str]:
    """Return ``(filename_suffix, content)`` for one harness bundle."""
    from skills.mcp import render_toml_fragment, to_harness_block

    spec = catalog.harnesses[harness]
    key = str(spec.get("config_key") or "mcpServers")
    servers = [s for s in catalog.servers if harness in s.harnesses]
    blocks = [(s.id, to_harness_block(s, harness, ".")) for s in servers]
    if spec.get("format") == "toml":
        return ".toml", render_toml_fragment(blocks, table=key)
    if spec.get("format") == "yaml":
        from skills.mcp import render_yaml_fragment
        return ".yaml", render_yaml_fragment(blocks)
    return ".json", json.dumps({key: dict(blocks)}, indent=2) + "\n"


def cmd_generate(args: argparse.Namespace) -> int:
    catalog = _load()
    problems = verify_catalog(catalog)
    if problems:
        print("[FAIL] refusing to generate from an invalid catalog:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    for harness in harness_names(catalog):
        suffix, content = _render_harness_bundle(catalog, harness)
        target = GENERATED_DIR / f"{harness}{suffix}"
        target.write_text(content, encoding="utf-8")
        written.append(str(target.relative_to(ROOT)))
        for stale in (".json", ".toml", ".yaml"):
            if stale != suffix:
                (GENERATED_DIR / f"{harness}{stale}").unlink(missing_ok=True)

    doc = _render_catalog_doc(catalog)
    previous = CATALOG_DOC.read_text(encoding="utf-8") if CATALOG_DOC.exists() else ""
    CATALOG_DOC.write_text(doc, encoding="utf-8")
    if previous != doc:
        written.append(str(CATALOG_DOC.relative_to(ROOT)))

    summary_path = ROOT / "mcps" / "summary.json"
    summary_path.write_text(json.dumps(catalog_summary(catalog), indent=2) + "\n", encoding="utf-8")
    written.append(str(summary_path.relative_to(ROOT)))

    if args.verify:
        return 0
    print(f"Generated {len(written)} file(s) from {len(catalog.servers)} MCP servers:")
    for path in written:
        print(f"  {path}")
    return 0


def cmd_sync_optin(args: argparse.Namespace) -> int:
    """Union the catalog into the plugin's opt-in connector file (additive only)."""
    catalog = _load()
    path = ROOT / "mcp-configs" / "mcp-servers.json"
    data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"mcpServers": {}}
    servers = data.setdefault("mcpServers", {})
    added = []
    for server in catalog.servers:
        if server.id in servers:
            continue
        block = server.config_block(".")
        block["description"] = server.description
        if server.required_env:
            block["env"] = {name: f"YOUR_{name}_HERE" for name in server.required_env}
        servers[server.id] = block
        added.append(server.id)
    data["mcpServers"] = dict(sorted(servers.items()))
    if added and not args.dry_run:
        path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"{'Would add' if args.dry_run else 'Added'} {len(added)} connector(s) to "
          f"{path.relative_to(ROOT)} (total {len(servers)}).")
    if added:
        print("  " + ", ".join(added))
    return 0


def _print_result(result: InstallResult, catalog: Catalog) -> None:
    verb = "would write" if result.dry_run else ("wrote" if result.written else "no change to")
    print(f"\n[{result.harness} / {result.scope}] {verb} {result.path}")
    if result.added:
        print(f"  install ({len(result.added)}): {', '.join(result.added)}")
    if result.unchanged:
        print(f"  already present ({len(result.unchanged)}): {', '.join(result.unchanged)}")
    if result.backup:
        print(f"  backup: {result.backup}")
    for name, reason in result.skipped:
        print(f"  skipped {name}: {reason}")
    if result.fragment is not None:
        print("  this harness uses a non-JSON config; paste the fragment below into its config file:")
        print("\n" + "\n".join("    " + line for line in result.fragment.splitlines()))
    needs = sorted({env for name in result.added if (srv := catalog.get(name)) for env in srv.required_placeholders()})
    if needs:
        print(f"  set these before first use: {', '.join(needs)}")


def cmd_install(args: argparse.Namespace) -> int:
    catalog = _load()
    try:
        if args.servers:
            servers = catalog.resolve(args.servers)
        elif args.profile:
            servers = expand_profile(catalog, args.profile)
        else:
            servers = expand_profile(catalog, "standard")
    except CatalogError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    harness_list = [args.harness] if args.harness else ["claude"]
    failures = 0
    for harness in harness_list:
        try:
            result = plan_install(catalog, harness, servers, ROOT, scope=args.scope, workspace=args.workspace)
            apply_install(result, dry_run=args.dry_run)
        except CatalogError as exc:
            print(f"ERROR [{harness}]: {exc}", file=sys.stderr)
            failures += 1
            continue
        _print_result(result, catalog)
        if args.json:
            print(json.dumps(result.as_dict(), indent=2))
    if not args.dry_run and not args.json:
        print("\nVerify with: python scripts/mcp_catalog.py doctor")
    return 1 if failures else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="MCP catalog: list, verify, generate, install")
    sub = parser.add_subparsers(dest="command", required=True)

    p_list = sub.add_parser("list", help="List catalog servers")
    p_list.add_argument("--profile", choices=None, help="Only servers in this profile")
    p_list.add_argument("--tier", choices=["core", "standard", "full"])
    p_list.add_argument("--category")
    p_list.add_argument("--json", action="store_true")
    p_list.set_defaults(func=cmd_list)

    p_doctor = sub.add_parser("doctor", help="Health-check the catalog and credentials")
    p_doctor.set_defaults(func=cmd_doctor)

    p_verify = sub.add_parser("verify", help="Verify catalog coherence (CI mode)")
    p_verify.set_defaults(func=cmd_verify)

    p_gen = sub.add_parser("generate", help="Regenerate docs/MCP-CATALOG.md and per-harness bundles")
    p_gen.add_argument("--verify", action="store_true", help="Check for drift without failing on writes")
    p_gen.set_defaults(func=cmd_generate)

    p_sync = sub.add_parser("sync-optin", help="Union the catalog into mcp-configs/mcp-servers.json")
    p_sync.add_argument("--dry-run", action="store_true")
    p_sync.set_defaults(func=cmd_sync_optin)

    p_install = sub.add_parser("install", help="Install servers into a harness config")
    p_install.add_argument("--harness", help="Target harness (default: claude)")
    p_install.add_argument("--scope", choices=["project", "user"], default="project")
    p_install.add_argument("--profile", help="Install a profile: core, standard, full")
    p_install.add_argument("--servers", nargs="*", help="Explicit server ids")
    p_install.add_argument("--workspace", default=".", help="Value substituted for ${WORKSPACE}")
    p_install.add_argument("--dry-run", action="store_true")
    p_install.add_argument("--json", action="store_true")
    p_install.set_defaults(func=cmd_install)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
